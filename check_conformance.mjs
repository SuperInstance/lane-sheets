#!/usr/bin/env node
// Conformance harness for the browser port of the lane-sheet
// interpreter (docs/js/). Runs the JavaScript port over every fixture
// in docs/fixtures/ and diffs its traces against the Python-produced
// goldens byte-for-byte; negative fixtures must be refused with the
// expected error name. This is the interpreter leg of the Python
// run_conformance.py, replayed against the port.
//
//   node check_conformance.mjs
//
// Prints a per-fixture PASS/FAIL and a summary; regenerates
// docs/js/conformance-manifest.js (the numbers the deployment page
// displays) from the actual run. Exit 0 only if everything passes.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import * as common from "./docs/js/common.js";
import { runSheet } from "./docs/js/interpret.js";

const ROOT = dirname(fileURLToPath(import.meta.url));
const FIXTURES = join(ROOT, "docs", "fixtures");

const sheetFiles = readdirSync(FIXTURES)
  .filter((f) => f.endsWith(".sheet.json"))
  .sort();
const positives = sheetFiles.filter((f) => !f.startsWith("negative-"));
const negatives = sheetFiles.filter((f) => f.startsWith("negative-"));

const library = {};
for (const f of sheetFiles) {
  library[f.replace(".sheet.json", "")] = JSON.parse(
    readFileSync(join(FIXTURES, f), "utf-8")
  );
}
const resolver = common.mapResolver(library);

let posPassed = 0;
for (const f of positives) {
  const name = f.replace(".sheet.json", "");
  const sheet = library[name];
  const golden = readFileSync(join(FIXTURES, `${name}.golden.jsonl`), "utf-8");
  try {
    const lines = runSheet(sheet, resolver);
    const trace = lines.join("\n") + "\n";
    if (trace === golden) {
      posPassed++;
      console.log(`PASS ${name} (${lines.length} trace lines)`);
    } else {
      console.log(`FAIL ${name} -- trace != golden`);
      const got = trace.split("\n");
      const want = golden.split("\n");
      for (let i = 0; i < Math.max(got.length, want.length); i++) {
        if (got[i] !== want[i]) {
          console.log(`  line ${i + 1}:\n    got:  ${got[i]}\n    want: ${want[i]}`);
          break;
        }
      }
    }
  } catch (exc) {
    console.log(`FAIL ${name} -- refused unexpectedly: ${exc.name ?? exc}`);
  }
}

let negPassed = 0;
for (const f of negatives) {
  const name = f.replace(".sheet.json", "");
  const expected = JSON.parse(readFileSync(join(FIXTURES, `${name}.expected.json`), "utf-8"));
  try {
    runSheet(library[name], resolver);
    console.log(`FAIL ${name} -- accepted, expected refusal ${expected.error}`);
  } catch (exc) {
    if (exc instanceof common.LaneSheetError && exc.name === expected.error) {
      negPassed++;
      console.log(`PASS ${name} (refusal: ${expected.error})`);
    } else {
      console.log(
        `FAIL ${name} -- refused with ${exc.name ?? exc}, expected ${expected.error}`
      );
    }
  }
}

const total = positives.length + negatives.length;
const passed = posPassed + negPassed;
console.log(
  `BROWSER SUMMARY: ${passed}/${total} PASS ` +
    `(${posPassed}/${positives.length} positive traces byte-identical, ` +
    `${negPassed}/${negatives.length} refusals by name)`
);

const manifest = {
  positives: positives.length,
  positivesPassed: posPassed,
  negatives: negatives.length,
  negativesPassed: negPassed,
  harness: `node ${process.version}`,
  generatedAt: new Date().toISOString().slice(0, 10),
};
writeFileSync(
  join(ROOT, "docs", "js", "conformance-manifest.js"),
  "// Generated by check_conformance.mjs from an actual harness run.\n" +
    "// Do not hand-edit: the deployment page displays these numbers as\n" +
    "// the browser port's conformance record.\n" +
    `export const CONFORMANCE = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log(`manifest written: docs/js/conformance-manifest.js (${JSON.stringify(manifest)})`);

process.exit(passed === total ? 0 : 1);
